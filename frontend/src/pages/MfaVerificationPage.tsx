
import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useAuth } from '../context/AuthContext.js';

export const MfaVerificationPage: React.FC = () => {
  const { mfaChallenge, completeMfa, clearMfaChallenge } = useAuth();
  const navigate = useNavigate();

  const [code, setCode] = useState('');
  const [useRecoveryCode, setUseRecoveryCode] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  useEffect(() => {
    if (!mfaChallenge) {
      navigate('/login', { replace: true });
    }
  }, [mfaChallenge, navigate]);

  const handleCodeChange = (value: string) => {
    const sanitizedValue = useRecoveryCode
      ? value.toUpperCase().replace(/[^A-Z0-9-]/g, '').slice(0, 9)
      : value.replace(/\D/g, '').slice(0, 6);

    setCode(sanitizedValue);
    setErrorMsg('');
  };

  const handleSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();

    if (!mfaChallenge) {
      clearMfaChallenge();
      navigate('/login', { replace: true });
      return;
    }

    const trimmedCode = code.trim();

    if (!useRecoveryCode && !/^\d{6}$/.test(trimmedCode)) {
      setErrorMsg('Please enter a valid 6-digit authenticator code.');
      return;
    }

    if (useRecoveryCode && !/^[A-Z0-9]{4}-[A-Z0-9]{4}$/.test(trimmedCode)) {
      setErrorMsg('Please enter a valid recovery code in the format XXXX-XXXX.');
      return;
    }

    setErrorMsg('');
    setIsSubmitting(true);

    try {
      await completeMfa(trimmedCode, useRecoveryCode);
      navigate('/dashboard', { replace: true });
    } catch (err: unknown) {
      const message =
        err instanceof Error
          ? err.message
          : 'Invalid verification code. Please try again.';

      setErrorMsg(message);
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleCancel = () => {
    clearMfaChallenge();
    navigate('/login', { replace: true });
  };

  if (!mfaChallenge) {
    return null;
  }

  return (
    <div className="bg-surface font-sans text-on-surface min-h-screen relative flex flex-col justify-between selection:bg-secondary-container selection:text-on-secondary-container">
      <div className="pointer-events-none absolute inset-0 z-0 bg-[radial-gradient(#dfe8ff_1px,transparent_1px)] [background-size:24px_24px] opacity-60"></div>

      <header className="relative z-10 w-full pt-space-xl pb-space-md px-margin flex flex-col items-center">
        <div className="flex items-center gap-space-sm mb-space-sm">
          <div className="w-10 h-10 rounded-lg bg-primary flex items-center justify-center text-on-primary shadow-sm">
            <span className="material-symbols-outlined text-[24px]">shield</span>
          </div>
          <span className="font-title-lg text-title-lg text-primary tracking-tight font-bold">
            SecureOrg
          </span>
        </div>
      </header>

      <main className="relative z-10 w-full flex-1 flex flex-col items-center justify-center px-margin py-space-md">
        <div className="w-full max-w-md bg-surface-container-lowest rounded-2xl shadow-lg border border-outline-variant/30 p-space-lg relative overflow-hidden">
          <div className="absolute top-0 left-0 right-0 h-1 bg-gradient-to-r from-primary via-secondary to-primary-container"></div>

          <div className="flex flex-col items-center text-center mb-space-lg">
            <div className="w-14 h-14 rounded-2xl bg-secondary-container text-on-secondary-container flex items-center justify-center shadow-sm mb-space-sm">
              <span className="material-symbols-outlined text-[32px]">
                phonelink_lock
              </span>
            </div>

            <h1 className="font-headline-sm text-headline-sm text-on-surface font-bold">
              Two-Factor Authentication
            </h1>

            <p className="font-body-md text-on-surface-variant text-[13px] mt-1 max-w-xs">
              {useRecoveryCode
                ? 'Enter an unused one-time backup recovery code (format: XXXX-XXXX).'
                : `Enter the 6-digit TOTP code generated by your authenticator app for ${mfaChallenge.email || 'your account'}.`}
            </p>
          </div>

          {errorMsg && (
            <div
              role="alert"
              aria-live="polite"
              className="mb-space-md p-space-sm rounded-lg bg-error-container text-on-error-container flex items-center gap-space-sm text-[13px] font-medium border border-error/30"
            >
              <span className="material-symbols-outlined text-[18px]">
                error
              </span>
              <span>{errorMsg}</span>
            </div>
          )}

          <form onSubmit={handleSubmit} className="space-y-space-md">
            <div className="flex flex-col space-y-1 text-center">
              <label
                className="text-[12px] font-semibold text-on-surface"
                htmlFor="mfa-code"
              >
                {useRecoveryCode
                  ? 'Backup Recovery Code'
                  : '6-Digit Authenticator Code'}
              </label>

              <input
                id="mfa-code"
                type="text"
                inputMode={useRecoveryCode ? 'text' : 'numeric'}
                autoComplete={useRecoveryCode ? 'off' : 'one-time-code'}
                maxLength={useRecoveryCode ? 9 : 6}
                required
                autoFocus
                value={code}
                onChange={(e) => handleCodeChange(e.target.value)}
                placeholder={useRecoveryCode ? 'A3F8-921B' : '000000'}
                aria-invalid={Boolean(errorMsg)}
                aria-describedby={errorMsg ? 'mfa-error' : undefined}
                className="w-full h-14 text-center font-mono text-[26px] tracking-widest bg-surface-container-low border border-outline-variant/30 rounded-xl text-primary focus:outline-none focus:bg-surface-container-lowest focus:ring-2 focus:ring-secondary transition-all"
              />
            </div>

            <button
              type="submit"
              disabled={isSubmitting || !code.trim()}
              className="w-full h-12 bg-primary hover:bg-primary-container text-on-primary rounded-xl font-bold text-[14px] flex items-center justify-center gap-2 shadow-sm transition-all disabled:opacity-50"
            >
              <span className="material-symbols-outlined text-[18px]">
                lock_open
              </span>
              <span>
                {isSubmitting ? 'Verifying...' : 'Verify & Complete Sign In'}
              </span>
            </button>
          </form>

          <div className="mt-space-lg flex flex-col items-center gap-2 pt-space-sm border-t border-outline-variant/30">
            <button
              type="button"
              disabled={isSubmitting}
              onClick={() => {
                setUseRecoveryCode((previous) => !previous);
                setCode('');
                setErrorMsg('');
              }}
              className="text-[13px] font-semibold text-secondary hover:text-primary transition-colors flex items-center gap-1 disabled:opacity-50"
            >
              <span className="material-symbols-outlined text-[16px]">
                key
              </span>
              <span>
                {useRecoveryCode
                  ? 'Use 6-digit Authenticator app'
                  : 'Use a backup recovery code instead'}
              </span>
            </button>

            <button
              type="button"
              disabled={isSubmitting}
              onClick={handleCancel}
              className="text-[12px] text-on-surface-variant hover:text-on-surface transition-colors disabled:opacity-50"
            >
              Cancel and return to sign in
            </button>
          </div>
        </div>
      </main>

      <footer className="relative z-10 w-full py-4 text-center text-on-surface-variant text-[12px]">
        SecureOrg &copy; 2026 Addis Ababa Science and Technology University.
      </footer>
    </div>
  );
};
